/**
 * "shippinginfo, privacy, about_us:About Our Company" -> list of
 * ['page' => ..., 'label' => ..., 'url' => ...].
 *
 * A page name is restricted to the characters Zen Cart itself allows in
 * main_page, so nothing typed into the setting can reach a URL unencoded.
 *
 * @param string $text
 * @return array
 */
function llmstxt_info_pages($text)
{
    $labels = llmstxt_info_page_labels();
    $out = [];
    foreach (explode(',', (string)$text) as $entry) {
        $entry = trim($entry);
        if ($entry === '') {
            continue;
        }
        $label = '';
        $page = $entry;
        $colon = strpos($entry, ':');
        if ($colon !== false) {
            $page = trim(substr($entry, 0, $colon));
            $label = trim(substr($entry, $colon + 1));
        }
        $page = preg_replace('~[^0-9a-zA-Z_]~', '', $page);
        if ($page === '') {
            continue;
        }
        if ($label === '') {
            $label = $labels[$page] ?? ucwords(str_replace('_', ' ', $page));
        }
        $out[] = ['page' => $page, 'label' => $label, 'url' => llmstxt_link($page)];
    }
    return $out;
}

/**
