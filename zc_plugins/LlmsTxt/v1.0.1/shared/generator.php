/**
 * A configuration constant, with a default for when it is not defined.
 *
 * The portable form of zen_config(), which is v3.0.0 only.
 *
 * @param string $key
 * @param mixed  $default
 * @return mixed
 */
function llmstxt_cfg($key, $default = '')
{
    return defined($key) ? constant($key) : $default;
}

/**
 * Every setting the generator reads, normalized once.
 *
 * The keys mirror the configuration keys without their prefix. Values are
 * cast here so that nothing below has to re-check a string 'true' or a
 * negative count.
 *
 * @return array
 */
function llmstxt_settings()
{
    $bool = static function ($key, $default) {
        $v = llmstxt_cfg($key, $default ? 'true' : 'false');
        return ((string)$v === 'true' || (string)$v === '1');
    };
    $int = static function ($key, $default) {
        return max(0, (int)llmstxt_cfg($key, $default));
    };
    $choice = static function ($key, array $allowed, $default) {
        $v = strtolower(trim((string)llmstxt_cfg($key, $default)));
        return in_array($v, $allowed, true) ? $v : $default;
    };

    return [
        'enabled' => $bool('LLMSTXT_STATUS', true),
        'output' => $choice('LLMSTXT_OUTPUT', ['file', 'dynamic', 'both'], 'file'),
        'rebuild' => $choice('LLMSTXT_REBUILD', ['change', 'daily', 'weekly', 'monthly', 'manual'], 'change'),
        'summary' => trim((string)llmstxt_cfg('LLMSTXT_SUMMARY', '')),
        'notes' => trim((string)llmstxt_cfg('LLMSTXT_NOTES', '')),
        'language' => strtolower(trim((string)llmstxt_cfg('LLMSTXT_LANGUAGE', ''))),
        'info_pages' => trim((string)llmstxt_cfg('LLMSTXT_INFO_PAGES', 'shippinginfo,privacy,conditions,contact_us,site_map')),
        'categories' => $bool('LLMSTXT_INCLUDE_CATEGORIES', true),
        'category_depth' => $int('LLMSTXT_CATEGORY_DEPTH', 0),
        'exclude_categories' => llmstxt_id_list(llmstxt_cfg('LLMSTXT_EXCLUDE_CATEGORIES', '')),
        'products' => $bool('LLMSTXT_INCLUDE_PRODUCTS', true),
        'max_products' => $int('LLMSTXT_MAX_PRODUCTS', 200),
        'product_order' => $choice('LLMSTXT_PRODUCT_ORDER', ['sort', 'newest', 'bestsellers', 'name', 'viewed'], 'sort'),
        'prices' => $bool('LLMSTXT_INCLUDE_PRICES', true),
        'brands' => $bool('LLMSTXT_INCLUDE_BRANDS', true),
        'ezpages' => $bool('LLMSTXT_INCLUDE_EZPAGES', true),
        'sitemap' => trim((string)llmstxt_cfg('LLMSTXT_SITEMAP_URL', '')),
        'description_length' => max(40, $int('LLMSTXT_DESCRIPTION_LENGTH', 160)),
        'full' => $bool('LLMSTXT_FULL', false),
        'full_length' => max(200, $int('LLMSTXT_FULL_LENGTH', 1200)),
    ];
}

/**
 * "12, 15,3" -> [3, 12, 15]. Anything that is not a positive integer is dropped.
 *
 * @param mixed $text
 * @return int[]
 */
function llmstxt_id_list($text)
{
    $ids = [];
    foreach (preg_split('~[\s,;]+~', (string)$text) as $piece) {
        $n = (int)$piece;
        if ($n > 0) {
            $ids[$n] = $n;
        }
    }
    $ids = array_values($ids);
    sort($ids);
    return $ids;
}

/**
 * A hash of everything that changes the output without the catalog changing.
 * Stored with each build, so editing a setting makes the next check rebuild.
 *
 * @param array|null $settings
 * @return string
 */
function llmstxt_settings_hash($settings = null)
{
    if ($settings === null) {
        $settings = llmstxt_settings();
    }
    return sha1(LLMSTXT_VERSION . '|' . serialize($settings) . '|'
        . (string)llmstxt_cfg('STORE_NAME', '') . '|' . llmstxt_catalog_base() . '|'
        . (string)llmstxt_cfg('DEFAULT_CURRENCY', '') . '|' . (string)llmstxt_cfg('DEFAULT_LANGUAGE', ''));
}

