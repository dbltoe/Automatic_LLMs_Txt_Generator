/**
 * A short string that changes whenever the listable catalog changes.
 *
 * Aggregates only, so it is cheap enough to run from the storefront. A product
 * edit, add, delete or status change moves products_last_modified or the
 * count; the same for categories. EZ-Pages carry no timestamp, so only their
 * count is watched -- an edit to one is caught by the admin observer instead.
 *
 * @param object $db
 * @return string
 */
function llmstxt_fingerprint($db)
{
    $parts = [];

    $r = $db->Execute(
        "SELECT COUNT(*) AS n, MAX(products_last_modified) AS m, MAX(products_date_added) AS a
           FROM " . TABLE_PRODUCTS . "
          WHERE products_status = 1"
    );
    $parts[] = 'p' . (int)$r->fields['n'] . '|' . (string)$r->fields['m'] . '|' . (string)$r->fields['a'];

    $r = $db->Execute(
        "SELECT COUNT(*) AS n, MAX(last_modified) AS m, MAX(date_added) AS a
           FROM " . TABLE_CATEGORIES . "
          WHERE categories_status = 1"
    );
    $parts[] = 'c' . (int)$r->fields['n'] . '|' . (string)$r->fields['m'] . '|' . (string)$r->fields['a'];

    $r = $db->Execute(
        "SELECT COUNT(*) AS n, MAX(m.last_modified) AS m
           FROM " . TABLE_MANUFACTURERS . " m"
    );
    $f = is_array($r->fields) ? $r->fields : [];
    $parts[] = 'm' . (int)($f['n'] ?? 0) . '|' . (string)($f['m'] ?? '');

    $r = $db->Execute(
        "SELECT COUNT(*) AS n
           FROM " . TABLE_EZPAGES . "
          WHERE status_visible = 1"
    );
    $parts[] = 'e' . (int)$r->fields['n'];

    return sha1(implode(';', $parts));
}

