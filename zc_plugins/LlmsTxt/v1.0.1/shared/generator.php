<?php
/**
 * Automatic LLMs.txt Generator -- the generator, shared by the storefront and the admin.
 *
 * Everything that reads the catalog and turns it into Markdown lives here, as
 * plain prefixed functions. No namespace, no class, no autoloader: Zen Cart
 * registers PSR-4 plugin paths differently on v1.5.8 and v3.0.0, and no release
 * auto-loads a plugin's storefront function files at all, so every entry point
 * (the page, the init script, the admin page, the observer, the installer)
 * `require_once`s this file by its own __DIR__ path instead.
 *
 * Nothing here echoes and nothing here calls exit(): the functions return
 * strings and arrays, and the thin entry points decide what to do with them.
 * That is also what makes the whole file testable without a web server.
 *
 * Written for PHP 7.4 through 8.5: no match, no nullsafe, no named arguments,
 * no union types, no str_contains(); every parameter that may be null says so.
 *
 * The output follows https://llmstxt.org/ -- one H1, one blockquote summary,
 * optional free text, then H2 sections each holding a list of
 * "- [name](url): notes" lines.
 *
 * @package  LlmsTxt
 * @license  http://www.zen-cart.com/license/2_0.txt GNU Public License V2.0
 */

