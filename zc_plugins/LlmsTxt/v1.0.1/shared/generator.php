/**
 * The language the file is written in: the configured code, else the store
 * default, else languages_id 1.
 *
 * @param object $db
 * @param array  $settings
 * @return int
 */
function llmstxt_language_id($db, array $settings)
{
    $codes = [];
    if ($settings['language'] !== '') {
        $codes[] = $settings['language'];
    }
    $default = strtolower((string)llmstxt_cfg('DEFAULT_LANGUAGE', 'en'));
    if ($default !== '' && !in_array($default, $codes, true)) {
        $codes[] = $default;
    }

    foreach ($codes as $code) {
        $r = $db->Execute(
            "SELECT languages_id FROM " . TABLE_LANGUAGES . "
              WHERE code = '" . $db->prepare_input($code) . "'
              LIMIT 1"
        );
        if (!$r->EOF) {
            return (int)$r->fields['languages_id'];
        }
    }
    return 1;
}

/**
 * The default currency's formatting row, or null if it cannot be found.
 *
 * @param object $db
 * @return array|null
 */
function llmstxt_default_currency($db)
{
    $code = (string)llmstxt_cfg('DEFAULT_CURRENCY', '');
    if ($code === '') {
        return null;
    }
    $r = $db->Execute(
        "SELECT code, symbol_left, symbol_right, decimal_point, thousands_point, decimal_places, value
           FROM " . TABLE_CURRENCIES . "
          WHERE code = '" . $db->prepare_input($code) . "'
          LIMIT 1"
    );
    if ($r->EOF) {
        return null;
    }
    $row = $r->fields;
    $row['value'] = ((float)$row['value'] > 0) ? (float)$row['value'] : 1.0;
    return $row;
}

/**
 * Every category, keyed by id, with its name, description, parent, status and
 * sort order. One query, then the tree is walked in PHP.
 *
 * @param object $db
 * @param int    $languageId
 * @return array
 */
function llmstxt_read_categories($db, $languageId)
{
    $rows = [];
    $r = $db->Execute(
        "SELECT c.categories_id, c.parent_id, c.sort_order, c.categories_status,
                cd.categories_name, cd.categories_description
           FROM " . TABLE_CATEGORIES . " c
                LEFT JOIN " . TABLE_CATEGORIES_DESCRIPTION . " cd
                    ON cd.categories_id = c.categories_id
                   AND cd.language_id = " . (int)$languageId . "
          ORDER BY c.parent_id, c.sort_order, cd.categories_name"
    );
    while (!$r->EOF) {
        $id = (int)$r->fields['categories_id'];
        $rows[$id] = [
            'id' => $id,
            'parent' => (int)$r->fields['parent_id'],
            'name' => (string)$r->fields['categories_name'],
            'description' => (string)$r->fields['categories_description'],
            'status' => ((int)$r->fields['categories_status'] === 1),
            'sort' => (int)$r->fields['sort_order'],
        ];
        $r->MoveNext();
    }
    return $rows;
}

/**
 * Walk the category tree and return the ones to list, in tree order, each
 * with its full path ("Hardware > Cables") and depth.
 *
 * A category is listed only when it and every ancestor are enabled, none of
 * them is excluded, and it has a name. `category_depth` 0 means every level.
 *
 * The returned 'visible' set (every listable category, regardless of the
 * depth cut) is what product selection uses, so a product is listed only when
 * its master category would be reachable on the storefront.
 *
 * @param array $categories  from llmstxt_read_categories()
 * @param array $settings
 * @return array  ['list' => [...], 'visible' => [id => true]]
 */
function llmstxt_category_tree(array $categories, array $settings)
{
    $children = [];
    foreach ($categories as $id => $c) {
        $children[$c['parent']][] = $id;
    }
    $excluded = array_flip($settings['exclude_categories']);
    $maxDepth = (int)$settings['category_depth'];

    $list = [];
    $visible = [];

    $walk = static function ($parent, $path, $depth) use (&$walk, &$list, &$visible, $children, $categories, $excluded, $maxDepth) {
        if (empty($children[$parent])) {
            return;
        }
        $ids = $children[$parent];
        usort($ids, static function ($a, $b) use ($categories) {
            if ($categories[$a]['sort'] !== $categories[$b]['sort']) {
                return $categories[$a]['sort'] <=> $categories[$b]['sort'];
            }
            return strcasecmp($categories[$a]['name'], $categories[$b]['name']);
        });
        foreach ($ids as $id) {
            $c = $categories[$id];
            if (!$c['status'] || isset($excluded[$id]) || trim($c['name']) === '') {
                continue;
            }
            $fullPath = ($path === '') ? $c['name'] : $path . ' > ' . $c['name'];
            $visible[$id] = true;
            if ($maxDepth === 0 || $depth <= $maxDepth) {
                $list[] = [
                    'id' => $id,
                    'name' => $c['name'],
                    'path' => $fullPath,
                    'depth' => $depth,
                    'description' => $c['description'],
                ];
            }
            $walk($id, $fullPath, $depth + 1);
        }
    };
    $walk(0, '', 1);

    return ['list' => $list, 'visible' => $visible];
}

/**
 * The products to list, already filtered to those a shopper could reach.
 *
 * The meta-tag description is preferred over the body text when the owner has
 * written one, because it is the sentence they chose to describe the product
 * to a machine.
 *
 * @param object $db
 * @param int    $languageId
 * @param array  $settings
 * @param array  $visibleCategories  [id => true]
 * @return array
 */
function llmstxt_read_products($db, $languageId, array $settings, array $visibleCategories)
{
    switch ($settings['product_order']) {
        case 'newest':
            $order = 'p.products_date_added DESC, pd.products_name';
            break;
        case 'bestsellers':
            $order = 'p.products_ordered DESC, pd.products_name';
            break;
        case 'name':
            $order = 'pd.products_name';
            break;
        case 'viewed':
            $order = 'pd.products_viewed DESC, pd.products_name';
            break;
        default:
            $order = 'p.products_sort_order, pd.products_name';
    }

    $products = [];
    $r = $db->Execute(
        "SELECT p.products_id, p.products_model, p.products_price, p.master_categories_id,
                p.products_type, pt.type_handler,
                pd.products_name, pd.products_description,
                mt.metatags_description
           FROM " . TABLE_PRODUCTS . " p
                LEFT JOIN " . TABLE_PRODUCTS_DESCRIPTION . " pd
                    ON pd.products_id = p.products_id
                   AND pd.language_id = " . (int)$languageId . "
                LEFT JOIN " . TABLE_META_TAGS_PRODUCTS_DESCRIPTION . " mt
                    ON mt.products_id = p.products_id
                   AND mt.language_id = " . (int)$languageId . "
                LEFT JOIN " . TABLE_PRODUCT_TYPES . " pt
                    ON pt.type_id = p.products_type
          WHERE p.products_status = 1
          ORDER BY " . $order
    );

    $limit = (int)$settings['max_products'];
    while (!$r->EOF) {
        $master = (int)$r->fields['master_categories_id'];
        $name = trim((string)$r->fields['products_name']);
        if ($name !== '' && ($master === 0 || isset($visibleCategories[$master]))) {
            $handler = trim((string)$r->fields['type_handler']);
            $products[] = [
                'id' => (int)$r->fields['products_id'],
                'name' => $name,
                'model' => trim((string)$r->fields['products_model']),
                'price' => (float)$r->fields['products_price'],
                'category' => $master,
                'page' => ($handler !== '' ? $handler : 'product') . '_info',
                'description' => (string)$r->fields['products_description'],
                'meta' => trim((string)$r->fields['metatags_description']),
            ];
            if ($limit > 0 && count($products) >= $limit) {
                break;
            }
        }
        $r->MoveNext();
    }
    return $products;
}

/**
 * Manufacturers ("brands") with at least one enabled product, in name order,
 * each with its product count. Products in hidden or excluded categories are
 * not counted, so a brand whose only products sit in an excluded category is
 * left out, as the products themselves are. The link is the manufacturer
 * listing on the index page, which every release serves.
 *
 * @param object $db
 * @param array  $visibleCategories  id => true, from llmstxt_category_tree()
 * @return array
 */
function llmstxt_read_brands($db, array $visibleCategories)
{
    $brands = [];
    $r = $db->Execute(
        "SELECT m.manufacturers_id, m.manufacturers_name, p.master_categories_id
           FROM " . TABLE_MANUFACTURERS . " m
                INNER JOIN " . TABLE_PRODUCTS . " p
                    ON p.manufacturers_id = m.manufacturers_id
                   AND p.products_status = 1
          ORDER BY m.manufacturers_name, m.manufacturers_id"
    );
    while (!$r->EOF) {
        $id = (int)$r->fields['manufacturers_id'];
        $name = trim((string)$r->fields['manufacturers_name']);
        $master = (int)$r->fields['master_categories_id'];
        if ($name !== '' && ($master === 0 || isset($visibleCategories[$master]))) {
            if (!isset($brands[$id])) {
                $brands[$id] = ['id' => $id, 'name' => $name, 'count' => 0];
            }
            $brands[$id]['count']++;
        }
        $r->MoveNext();
    }
    return array_values($brands);
}

/**
 * Published EZ-Pages that appear somewhere on the storefront, in header order.
 *
 * `status_visible` is the published flag; a page nobody has put in the header,
 * a sidebox, the footer or the table of contents is left out too, since the
 * storefront offers no way to reach it. status_mobile is not consulted: it
 * does not exist on v1.5.8.
 *
 * @param object $db
 * @param int    $languageId
 * @return array
 */
function llmstxt_read_ezpages($db, $languageId)
{
    $pages = [];
    $r = $db->Execute(
        "SELECT e.pages_id, e.alt_url, e.alt_url_external, e.toc_chapter,
                e.header_sort_order, e.footer_sort_order, e.sidebox_sort_order,
                c.pages_title, c.pages_html_text
           FROM " . TABLE_EZPAGES . " e
                LEFT JOIN " . TABLE_EZPAGES_CONTENT . " c
                    ON c.pages_id = e.pages_id
                   AND c.languages_id = " . (int)$languageId . "
          WHERE e.status_visible = 1
            AND (e.status_header = 1 OR e.status_sidebox = 1 OR e.status_footer = 1 OR e.status_toc = 1)
          ORDER BY e.header_sort_order, e.footer_sort_order, e.sidebox_sort_order, c.pages_title"
    );
    while (!$r->EOF) {
        $title = trim((string)$r->fields['pages_title']);
        if ($title !== '') {
            $external = trim((string)$r->fields['alt_url_external']);
            $alt = trim((string)$r->fields['alt_url']);
            $id = (int)$r->fields['pages_id'];
            if ($external !== '') {
                $url = $external;
            } elseif ($alt !== '') {
                $url = llmstxt_link($alt);
            } else {
                $params = 'id=' . $id;
                if ((int)$r->fields['toc_chapter'] > 0) {
                    $params .= '&chapter=' . (int)$r->fields['toc_chapter'];
                }
                $url = llmstxt_link(llmstxt_cfg('FILENAME_EZPAGES', 'page'), $params);
            }
            $pages[] = [
                'id' => $id,
                'title' => $title,
                'url' => $url,
                'external' => ($external !== ''),
                'text' => (string)$r->fields['pages_html_text'],
            ];
        }
        $r->MoveNext();
    }
    return $pages;
}

