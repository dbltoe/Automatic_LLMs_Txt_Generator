/**
 * Gather everything the two renderers need. One pass over the database.
 *
 * @param object     $db
 * @param array|null $settings
 * @return array
 */
function llmstxt_collect($db, $settings = null)
{
    if ($settings === null) {
        $settings = llmstxt_settings();
    }
    $languageId = llmstxt_language_id($db, $settings);

    $data = [
        'settings' => $settings,
        'language_id' => $languageId,
        // Configuration values are stored with HTML entities on some releases
        // ("Stoke &amp; Trent"), and this is a text file, not an HTML page.
        'store_name' => llmstxt_store_name(),
        'base_url' => llmstxt_catalog_base(),
        'currency' => llmstxt_default_currency($db),
        'currency_code' => (string)llmstxt_cfg('DEFAULT_CURRENCY', ''),
        'sitemap' => llmstxt_sitemap_url($settings),
        'robots' => llmstxt_robots_url(),
        'info_pages' => llmstxt_info_pages($settings['info_pages']),
        'categories' => [],
        'brands' => [],
        'products' => [],
        'ezpages' => [],
    ];

    $visible = [];
    if ($settings['categories'] || $settings['products'] || $settings['brands']) {
        $tree = llmstxt_category_tree(llmstxt_read_categories($db, $languageId), $settings);
        $visible = $tree['visible'];
        if ($settings['categories']) {
            $data['categories'] = $tree['list'];
        }
    }
    if ($settings['brands']) {
        $data['brands'] = llmstxt_read_brands($db, $visible);
    }
    if ($settings['products']) {
        $data['products'] = llmstxt_read_products($db, $languageId, $settings, $visible);
    }
    if ($settings['ezpages']) {
        $data['ezpages'] = llmstxt_read_ezpages($db, $languageId);
    }

    // Extension point: an observer may add to or change anything collected.
    llmstxt_notify('NOTIFY_LLMSTXT_COLLECT_END', $settings, $data);

    return $data;
}

/**
 * The store name for the H1. Configuration values can be stored with HTML
 * entities ("Stoke &amp; Trent"), and this is a text file, so they are
 * decoded. A store that has not set its name yet (the first build runs at
 * install time) gets its host name rather than an empty heading.
 *
 * @return string
 */
function llmstxt_store_name()
{
    $name = llmstxt_text(llmstxt_cfg('STORE_NAME', ''));
    if ($name !== '') {
        return $name;
    }
    $host = (string)parse_url(llmstxt_catalog_base(), PHP_URL_HOST);
    return $host !== '' ? $host : 'Online Store';
}

/**
 * A heading constant with a default, so a translation can rename any section.
 */
function llmstxt_heading($key, $default)
{
    $v = llmstxt_cfg($key, $default);
    return trim(str_replace(["\r", "\n"], ' ', (string)$v));
}

/**
 * The store's one-sentence summary for the blockquote.
 */
function llmstxt_summary(array $data)
{
    $summary = $data['settings']['summary'];
    if ($summary === '') {
        $summary = sprintf(llmstxt_cfg('LLMSTXT_DEFAULT_SUMMARY', '%s is an online store.'), $data['store_name']);
    }
    // One line, with any entities the admin editor stored turned back into
    // characters. Tags are left alone: the owner may want none, but this is
    // their text and Markdown tolerates inline HTML.
    $summary = html_entity_decode($summary, ENT_QUOTES | ENT_HTML5, 'UTF-8');
    return trim(preg_replace('~\s+~', ' ', str_replace(["\r\n", "\r"], "\n", $summary)));
}

/**
 * Render llms.txt (or, with $full, llms-full.txt) from collected data.
 *
 * @param array $data  from llmstxt_collect()
 * @param bool  $full
 * @return string
 */
function llmstxt_render(array $data, $full = false)
{
    $s = $data['settings'];
    $out = [];

    $out[] = '# ' . llmstxt_label($data['store_name']);
    $out[] = '';
    $out[] = '> ' . llmstxt_summary($data);
    $out[] = '';

    if ($s['notes'] !== '') {
        // The owner's own Markdown, passed through as written apart from
        // undoing the entity encoding the admin editor may have applied.
        $out[] = trim(str_replace(["\r\n", "\r"], "\n", html_entity_decode($s['notes'], ENT_QUOTES | ENT_HTML5, 'UTF-8')));
        $out[] = '';
    }

    $out[] = llmstxt_item(llmstxt_heading('LLMSTXT_LABEL_WEBSITE', 'Website'), $data['base_url']);
    if ($data['currency_code'] !== '') {
        $out[] = '- ' . llmstxt_heading('LLMSTXT_LABEL_CURRENCY', 'Prices are in') . ': ' . llmstxt_label($data['currency_code']);
    }
    if ($data['sitemap'] !== '') {
        $out[] = llmstxt_item(llmstxt_heading('LLMSTXT_LABEL_SITEMAP', 'Sitemap'), $data['sitemap']);
    }
    if ($data['robots'] !== '') {
        $out[] = llmstxt_item(llmstxt_heading('LLMSTXT_LABEL_ROBOTS', 'Robots'), $data['robots']);
    }
    if (!$full && $s['full']) {
        $out[] = llmstxt_item(
            llmstxt_heading('LLMSTXT_LABEL_FULL', 'Full catalog listing'),
            $data['base_url'] . 'llms-full.txt',
            llmstxt_heading('LLMSTXT_NOTE_FULL', 'the same sections with complete descriptions')
        );
    }
    $out[] = '';

    if ($data['info_pages'] !== []) {
        $out[] = '## ' . llmstxt_heading('LLMSTXT_HEADING_INFO', 'Shopping information');
        $out[] = '';
        foreach ($data['info_pages'] as $page) {
            $out[] = llmstxt_item($page['label'], $page['url']);
        }
        $out[] = '';
    }

    if ($data['categories'] !== []) {
        $out[] = '## ' . llmstxt_heading('LLMSTXT_HEADING_CATEGORIES', 'Categories');
        $out[] = '';
        foreach ($data['categories'] as $c) {
            $url = llmstxt_link('index', 'cPath=' . $c['id']);
            $notes = llmstxt_text($c['description'], $full ? $s['full_length'] : $s['description_length']);
            $out[] = llmstxt_item($c['path'], $url, $notes);
        }
        $out[] = '';
    }

    if ($data['brands'] !== []) {
        $out[] = '## ' . llmstxt_heading('LLMSTXT_HEADING_BRANDS', 'Brands');
        $out[] = '';
        foreach ($data['brands'] as $b) {
            $url = llmstxt_link('index', 'manufacturers_id=' . $b['id']);
            $notes = ($b['count'] === 1)
                ? llmstxt_heading('LLMSTXT_NOTE_BRAND_ONE', '1 product')
                : sprintf(llmstxt_heading('LLMSTXT_NOTE_BRAND_MANY', '%d products'), $b['count']);
            $out[] = llmstxt_item($b['name'], $url, $notes);
        }
        $out[] = '';
    }

    if ($data['products'] !== []) {
        $out[] = '## ' . llmstxt_heading('LLMSTXT_HEADING_PRODUCTS', 'Products');
        $out[] = '';
        foreach ($data['products'] as $p) {
            $url = llmstxt_link($p['page'], 'products_id=' . $p['id']);
            $source = ($p['meta'] !== '') ? $p['meta'] : $p['description'];
            $notes = llmstxt_text($source, $full ? $s['full_length'] : $s['description_length']);
            $extras = [];
            if ($s['prices'] && $p['price'] > 0) {
                $extras[] = llmstxt_format_price($p['price'], $data['currency']);
            }
            if ($full && $p['model'] !== '') {
                $extras[] = llmstxt_heading('LLMSTXT_LABEL_MODEL', 'Model') . ' ' . $p['model'];
            }
            if ($extras !== []) {
                // Escaped once, with the rest of the notes, by llmstxt_item().
                $notes = ($notes === '' ? '' : $notes . ' ') . '(' . implode('; ', $extras) . ')';
            }
            $out[] = llmstxt_item($p['name'], $url, $notes);
        }
        $out[] = '';
    }

    if ($data['ezpages'] !== []) {
        $out[] = '## ' . llmstxt_heading('LLMSTXT_HEADING_PAGES', 'More pages');
        $out[] = '';
        foreach ($data['ezpages'] as $page) {
            $notes = $full ? llmstxt_text($page['text'], $s['full_length']) : '';
            $out[] = llmstxt_item($page['title'], $page['url'], $notes);
        }
        $out[] = '';
    }

    // Extension point: $out is the list of lines so far. The marker comment
    // is added afterwards so it always closes the file.
    llmstxt_notify('NOTIFY_LLMSTXT_RENDER_END', ['full' => $full, 'data' => $data], $out);

    $out[] = '<!-- ' . LLMSTXT_MARKER . ' ' . LLMSTXT_VERSION . ' on ' . gmdate('Y-m-d H:i') . ' UTC -->';

    return implode("\n", $out) . "\n";
}

/**
 * Collect and render in one call.
 *
 * @param object     $db
 * @param array|null $settings
 * @return array ['llms' => string, 'full' => string|null, 'fingerprint' => string, 'settings_hash' => string, 'counts' => array]
 */
function llmstxt_build($db, $settings = null)
{
    if ($settings === null) {
        $settings = llmstxt_settings();
    }
    $data = llmstxt_collect($db, $settings);
    return [
        'llms' => llmstxt_render($data, false),
        'full' => $settings['full'] ? llmstxt_render($data, true) : null,
        'fingerprint' => llmstxt_fingerprint($db),
        'settings_hash' => llmstxt_settings_hash($settings),
        'counts' => [
            'categories' => count($data['categories']),
            'brands' => count($data['brands']),
            'products' => count($data['products']),
            'ezpages' => count($data['ezpages']),
            'info_pages' => count($data['info_pages']),
        ],
    ];
}

