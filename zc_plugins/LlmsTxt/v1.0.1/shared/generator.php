/**
 * The state file: when the last build ran, what it saw, and whether a change
 * has been flagged since. Lives in the cache directory, which Zen Cart already
 * requires to be writable, so it works on a store whose root is not.
 *
 * @return array
 */
function llmstxt_read_state()
{
    $defaults = [
        'built' => 0,
        'checked' => 0,
        'lock' => 0,
        'dirty' => false,
        'dirty_reason' => '',
        'fingerprint' => '',
        'settings_hash' => '',
        'file_sha1' => '',
        'full_sha1' => '',
        'takeover' => false,
        'last_error' => '',
        'last_reason' => '',
        'counts' => [],
    ];
    $path = llmstxt_state_path();
    if (!is_file($path)) {
        return $defaults;
    }
    $raw = (string)file_get_contents($path);
    // A byte-order mark, which an editor or a Windows tool may add, is not
    // JSON. Tolerated rather than treated as a corrupt file.
    if (strpos($raw, "\xEF\xBB\xBF") === 0) {
        $raw = substr($raw, 3);
    }
    $json = json_decode($raw, true);
    if (!is_array($json)) {
        return $defaults;
    }
    return array_merge($defaults, $json);
}

/**
 * @param array $state
 * @return bool
 */
function llmstxt_write_state(array $state)
{
    return llmstxt_write_file(llmstxt_state_path(), (string)json_encode($state, JSON_PRETTY_PRINT));
}

/**
 * Write a file in one step: to a temporary name first, then renamed over the
 * target, so a crawler never reads a half-written llms.txt.
 *
 * @param string $path
 * @param string $content
 * @return bool
 */
function llmstxt_write_file($path, $content)
{
    $dir = dirname($path);
    if (!is_dir($dir) || !is_writable($dir)) {
        return false;
    }
    if (is_file($path) && !is_writable($path)) {
        return false;
    }
    $tmp = $dir . '/.' . basename($path) . '.' . substr(sha1(uniqid('', true)), 0, 8) . '.tmp';
    if (file_put_contents($tmp, $content, LOCK_EX) === false) {
        return false;
    }
    // rename() over an existing file is atomic on POSIX; on Windows it can
    // refuse, so the target is removed first there and only there.
    if (!@rename($tmp, $path)) {
        if (is_file($path)) {
            @unlink($path);
        }
        if (!@rename($tmp, $path)) {
            @unlink($tmp);
            return false;
        }
    }
    return true;
}

/**
 * Does a file at the store root belong to this plugin?
 *
 * Yes if its hash matches what the last build recorded, or if it carries the
 * marker line -- the second test survives a cleared cache directory. A file
 * that fails both was put there by somebody else and is never overwritten
 * unless the owner has said so from the admin page.
 *
 * @param string $path
 * @param array  $state
 * @param bool   $full
 * @return bool
 */
function llmstxt_file_is_ours($path, array $state, $full = false)
{
    if (!is_file($path)) {
        return true;
    }
    $content = (string)file_get_contents($path);
    $recorded = $full ? (string)$state['full_sha1'] : (string)$state['file_sha1'];
    if ($recorded !== '' && sha1($content) === $recorded) {
        return true;
    }
    return strpos($content, LLMSTXT_MARKER) !== false;
}

/**
 * A description of a file at the store root, for the admin page.
 *
 * @param bool  $full
 * @param array $state
 * @return array
 */
function llmstxt_file_status($full, array $state)
{
    $path = llmstxt_file_path($full);
    $exists = is_file($path);
    return [
        'path' => $path,
        'exists' => $exists,
        'ours' => $exists ? llmstxt_file_is_ours($path, $state, $full) : true,
        'size' => $exists ? (int)filesize($path) : 0,
        'modified' => $exists ? (int)filemtime($path) : 0,
        'writable' => $exists ? is_writable($path) : is_writable(dirname($path)),
    ];
}

/**
 * The rebuild interval for the timed policies, in seconds. 0 for the others.
 *
 * @param string $policy
 * @return int
 */
function llmstxt_policy_interval($policy)
{
    switch ($policy) {
        case 'daily':
            return 86400;
        case 'weekly':
            return 7 * 86400;
        case 'monthly':
            return 30 * 86400;
    }
    return 0;
}

/**
 * Should the storefront rebuild now? Returns the reason, or '' for no.
 *
 * Every policy rebuilds when nothing has ever been built, when a setting has
 * changed, or when the admin observer has flagged a change. The 'change'
 * policy also compares the catalog fingerprint; the timed policies wait for
 * their interval; 'manual' never rebuilds on its own.
 *
 * @param array       $state
 * @param array       $settings
 * @param string|null $fingerprint  pass null to skip the catalog comparison
 * @param int         $now
 * @return string
 */
function llmstxt_rebuild_reason(array $state, array $settings, $fingerprint, $now)
{
    if ((int)$state['built'] === 0) {
        return 'never built';
    }
    if ((string)$state['settings_hash'] !== llmstxt_settings_hash($settings)) {
        return 'settings changed';
    }
    if (!empty($state['dirty'])) {
        return 'catalog changed' . ((string)$state['dirty_reason'] !== '' ? ' (' . $state['dirty_reason'] . ')' : '');
    }
    if ($settings['rebuild'] === 'manual') {
        return '';
    }
    $interval = llmstxt_policy_interval($settings['rebuild']);
    if ($interval > 0) {
        return ((int)$state['built'] + $interval <= $now) ? 'scheduled (' . $settings['rebuild'] . ')' : '';
    }
    if ($fingerprint !== null && (string)$state['fingerprint'] !== (string)$fingerprint) {
        return 'catalog changed';
    }
    return '';
}

/**
 * Flag that the catalog has changed, from the admin observer. Cheap: one small
 * file write, no build. The next storefront check, or the next dynamic
 * request, does the work.
 *
 * @param string $reason
 * @return void
 */
function llmstxt_mark_dirty($reason = '')
{
    $state = llmstxt_read_state();
    if (!empty($state['dirty'])) {
        return;
    }
    $state['dirty'] = true;
    $state['dirty_reason'] = (string)$reason;
    llmstxt_write_state($state);
}

/**
 * Build and publish according to the settings.
 *
 * Writes the dynamic cache always (it is cheap, and it means the page never
 * has to build under a crawler), writes llms.txt and llms-full.txt when the
 * output setting says so, and records the result. A foreign file at the root
 * is left alone unless the owner has asked for it to be replaced.
 *
 * @param object $db
 * @param string $reason   recorded in the state for the admin page
 * @param bool   $takeover replace a file this plugin did not write
 * @return array ['ok' => bool, 'wrote' => [paths], 'skipped' => [messages], 'error' => string, 'counts' => array]
 */
function llmstxt_publish($db, $reason = 'manual', $takeover = false)
{
    $settings = llmstxt_settings();
    $state = llmstxt_read_state();
    $now = time();

    $result = ['ok' => true, 'wrote' => [], 'skipped' => [], 'error' => '', 'counts' => []];

    $state['lock'] = $now;
    llmstxt_write_state($state);

    try {
        $built = llmstxt_build($db, $settings);
    } catch (Throwable $e) {
        $state['lock'] = 0;
        $state['last_error'] = 'build failed: ' . $e->getMessage();
        llmstxt_write_state($state);
        return ['ok' => false, 'wrote' => [], 'skipped' => [], 'error' => $state['last_error'], 'counts' => []];
    }

    // The dynamic page's copy.
    if (!llmstxt_write_file(llmstxt_cache_path(false), $built['llms'])) {
        $result['skipped'][] = 'cache directory not writable: ' . llmstxt_cache_dir();
    }
    if ($built['full'] !== null) {
        llmstxt_write_file(llmstxt_cache_path(true), $built['full']);
    } elseif (is_file(llmstxt_cache_path(true))) {
        @unlink(llmstxt_cache_path(true));
    }

    // The published files.
    if ($settings['output'] === 'file' || $settings['output'] === 'both') {
        $targets = [[false, $built['llms']]];
        if ($built['full'] !== null) {
            $targets[] = [true, $built['full']];
        }
        foreach ($targets as $t) {
            [$full, $content] = $t;
            $path = llmstxt_file_path($full);
            if (!$takeover && !$state['takeover'] && !llmstxt_file_is_ours($path, $state, $full)) {
                $result['skipped'][] = basename($path) . ' was not written by this plugin and has been left alone';
                continue;
            }
            if (llmstxt_write_file($path, $content)) {
                $result['wrote'][] = $path;
                $state[$full ? 'full_sha1' : 'file_sha1'] = sha1($content);
            } else {
                $result['ok'] = false;
                $result['error'] = 'could not write ' . $path;
            }
        }
        // A full file left over from when the setting was on would go stale.
        if ($built['full'] === null && is_file(llmstxt_file_path(true))
            && llmstxt_file_is_ours(llmstxt_file_path(true), $state, true)
        ) {
            @unlink(llmstxt_file_path(true));
            $state['full_sha1'] = '';
        }
    }

    $state['built'] = $now;
    $state['checked'] = $now;
    $state['lock'] = 0;
    $state['dirty'] = false;
    $state['dirty_reason'] = '';
    $state['fingerprint'] = $built['fingerprint'];
    $state['settings_hash'] = $built['settings_hash'];
    $state['takeover'] = $takeover ? true : (bool)$state['takeover'];
    $state['last_error'] = $result['error'];
    $state['last_reason'] = (string)$reason;
    $state['counts'] = $built['counts'];
    llmstxt_write_state($state);

    $result['counts'] = $built['counts'];

    // Extension point: a build has just been published (or failed to be).
    llmstxt_notify('NOTIFY_LLMSTXT_PUBLISHED', ['reason' => (string)$reason, 'takeover' => (bool)$takeover], $result);

    return $result;
}

/**
 * Remove the files this plugin wrote to the store root. Files it did not
 * write are never touched.
 *
 * @return array  basenames removed
 */
function llmstxt_remove_files()
{
    $state = llmstxt_read_state();
    $removed = [];
    foreach ([false, true] as $full) {
        $path = llmstxt_file_path($full);
        if (is_file($path) && llmstxt_file_is_ours($path, $state, $full) && @unlink($path)) {
            $removed[] = basename($path);
            $state[$full ? 'full_sha1' : 'file_sha1'] = '';
        }
    }
    foreach ([llmstxt_cache_path(false), llmstxt_cache_path(true)] as $cache) {
        if (is_file($cache)) {
            @unlink($cache);
        }
    }
    $state['built'] = 0;
    llmstxt_write_state($state);
    return $removed;
}

/**
 * The storefront's periodic look at whether a published file needs rebuilding.
 *
 * Called from the init script on every page view, so it returns immediately
 * in the common case: the plugin is off, the output is dynamic-only, the last
 * look was recent, or another request is already building. Never throws.
 *
 * @param object $db
 * @return string  what happened, for the tests; '' when nothing did
 */
function llmstxt_maintain($db)
{
    try {
        $settings = llmstxt_settings();
        if (!$settings['enabled'] || $settings['output'] === 'dynamic') {
            return '';
        }
        $state = llmstxt_read_state();
        $now = time();
        if ((int)$state['lock'] > 0 && (int)$state['lock'] + LLMSTXT_LOCK_TTL > $now) {
            return 'locked';
        }
        if ((int)$state['checked'] + LLMSTXT_CHECK_INTERVAL > $now) {
            return '';
        }

        $fingerprint = ($settings['rebuild'] === 'change') ? llmstxt_fingerprint($db) : null;
        $reason = llmstxt_rebuild_reason($state, $settings, $fingerprint, $now);

        // The file itself may have been deleted by hand since the last build.
        if ($reason === '' && (int)$state['built'] > 0 && !is_file(llmstxt_file_path(false))) {
            $reason = 'file missing';
        }

        if ($reason === '') {
            $state['checked'] = $now;
            llmstxt_write_state($state);
            return '';
        }

        llmstxt_publish($db, 'storefront: ' . $reason);
        return 'rebuilt: ' . $reason;
    } catch (Throwable $e) {
        // A maintenance failure must never take a storefront page down.
        return 'error: ' . $e->getMessage();
    }
}

/**
 * The body for a dynamic request, building first if the cached copy is
 * missing or due for a rebuild.
 *
 * @param object $db
 * @param bool   $full
 * @return array ['status' => int, 'body' => string]
 */
function llmstxt_serve($db, $full = false)
{
    $settings = llmstxt_settings();
    if (!$settings['enabled']) {
        return ['status' => 404, 'body' => ''];
    }
    if ($full && !$settings['full']) {
        return ['status' => 404, 'body' => ''];
    }

    $state = llmstxt_read_state();
    $now = time();
    $cache = llmstxt_cache_path($full);

    $reason = '';
    if (!is_file($cache)) {
        $reason = 'cache missing';
    } elseif ((int)$state['lock'] > 0 && (int)$state['lock'] + LLMSTXT_LOCK_TTL > $now) {
        $reason = '';
    } elseif ((int)$state['checked'] + LLMSTXT_CHECK_INTERVAL <= $now) {
        $fingerprint = ($settings['rebuild'] === 'change') ? llmstxt_fingerprint($db) : null;
        $reason = llmstxt_rebuild_reason($state, $settings, $fingerprint, $now);
        if ($reason === '') {
            $state['checked'] = $now;
            llmstxt_write_state($state);
        }
    }

    if ($reason !== '') {
        llmstxt_publish($db, 'request: ' . $reason);
    }

    if (is_file($cache)) {
        $response = ['status' => 200, 'body' => (string)file_get_contents($cache)];
    } else {
        // The cache directory could not be written; build for this request alone.
        try {
            $built = llmstxt_build($db, $settings);
            $response = ['status' => 200, 'body' => $full ? (string)$built['full'] : $built['llms']];
        } catch (Throwable $e) {
            $response = ['status' => 500, 'body' => ''];
        }
    }

    // Extension point: the file is about to be sent to a visitor.
    llmstxt_notify('NOTIFY_LLMSTXT_SERVE', ['full' => $full, 'status' => $response['status']]);

    return $response;
}
