/**
 * The storefront's base URL with a trailing slash, from whichever side is
 * running. The admin's configure.php names the storefront with the
 * *_CATALOG_SERVER constants; the storefront's names it with HTTP_SERVER.
 *
 * https is preferred whenever the store says it has it, because that is the
 * address a crawler should be given.
 *
 * @return string
 */
function llmstxt_catalog_base()
{
    if (defined('IS_ADMIN_FLAG') && IS_ADMIN_FLAG === true && defined('HTTP_CATALOG_SERVER')) {
        $ssl = (llmstxt_cfg('ENABLE_SSL_CATALOG', 'false') === 'true' && defined('HTTPS_CATALOG_SERVER') && HTTPS_CATALOG_SERVER !== '');
        $server = $ssl ? (string)HTTPS_CATALOG_SERVER : (string)HTTP_CATALOG_SERVER;
        $dir = defined('DIR_WS_CATALOG') ? (string)DIR_WS_CATALOG : '/';
    } else {
        $ssl = (llmstxt_cfg('ENABLE_SSL', 'false') === 'true' && defined('HTTPS_SERVER') && HTTPS_SERVER !== '');
        $server = $ssl ? (string)HTTPS_SERVER : (string)llmstxt_cfg('HTTP_SERVER', '');
        $dir = defined('DIR_WS_CATALOG') ? (string)DIR_WS_CATALOG : '/';
    }
    return rtrim($server, '/') . '/' . ltrim($dir, '/');
}

/**
 * A storefront URL for a page.
 *
 * On the storefront, zen_href_link() is used so that an SEO-URL plugin, which
 * overrides that function, gets to shape the address exactly as it does for
 * every other link on the site. No session id is ever added.
 *
 * In the admin, zen_href_link() builds ADMIN addresses, so the storefront form
 * is assembled by hand. A store running an SEO-URL plugin therefore gets plain
 * index.php addresses from an admin-triggered build and SEO addresses from a
 * storefront-triggered one; both resolve, and the readme says so.
 *
 * @param string $page   a main_page name
 * @param string $params query-string without the leading ?
 * @return string
 */
function llmstxt_link($page, $params = '')
{
    $page = (string)$page;
    $params = (string)$params;

    $inAdmin = (defined('IS_ADMIN_FLAG') && IS_ADMIN_FLAG === true);
    if (!$inAdmin && function_exists('zen_href_link')) {
        // zen_href_link() returns an address ready to sit in an HTML
        // attribute, so its parameter separator is &amp;. This is a text file.
        return html_entity_decode((string)zen_href_link($page, $params, 'NONSSL', false), ENT_QUOTES, 'UTF-8');
    }

    $url = llmstxt_catalog_base() . 'index.php?main_page=' . rawurlencode($page);
    if ($params !== '') {
        $url .= '&' . $params;
    }
    return $url;
}

/* ------------------------------------------------------------------ *
 * Text helpers
 * ------------------------------------------------------------------ */

/**
 * HTML -> one line of plain text, cut at a word boundary.
 *
 * Block-level tags become spaces first so "<p>One</p><p>Two</p>" does not read
 * "OneTwo". Entities are decoded, whitespace is collapsed, and a cut is marked
 * with a single ellipsis character.
 *
 * @param mixed $html
 * @param int   $maxLength  0 = no cut
 * @return string
 */
function llmstxt_text($html, $maxLength = 0)
{
    $text = (string)$html;
    $text = preg_replace('~<\s*(script|style)\b[^>]*>.*?<\s*/\s*\1\s*>~is', ' ', $text);
    $text = preg_replace('~<\s*(br|/p|/div|/li|/h[1-6]|/tr|/td|/th)\b[^>]*>~i', ' ', $text);
    $text = strip_tags($text);
    $text = html_entity_decode($text, ENT_QUOTES | ENT_HTML5, 'UTF-8');
    $text = str_replace(["\xC2\xA0", "\xE2\x80\x8B"], ' ', $text);
    $text = preg_replace('~\s+~u', ' ', $text);
    $text = trim((string)$text);

    if ($maxLength > 0 && llmstxt_strlen($text) > $maxLength) {
        $cut = llmstxt_substr($text, 0, $maxLength);
        $space = strrpos($cut, ' ');
        if ($space !== false && $space > (int)($maxLength * 0.6)) {
            $cut = substr($cut, 0, $space);
        }
        $text = rtrim($cut, " \t,;:-") . "\xE2\x80\xA6";
    }

    return $text;
}

/**
 * Multibyte-safe length and substring, without requiring ext/mbstring.
 */
function llmstxt_strlen($s)
{
    return function_exists('mb_strlen') ? mb_strlen($s, 'UTF-8') : strlen($s);
}

function llmstxt_substr($s, $start, $length)
{
    return function_exists('mb_substr') ? mb_substr($s, $start, $length, 'UTF-8') : substr($s, $start, $length);
}

/**
 * Backslash-escape the characters that carry meaning inside a Markdown line,
 * so a product called "50% off [Sale]" or "Model_K *new*" reads as written
 * instead of turning into a link, emphasis or a tag. Only inline syntax is
 * covered: "-", "#" and ">" matter at the start of a line, and nothing that
 * passes through here ever starts one. CommonMark treats a backslash before
 * any ASCII punctuation as the literal character, so the escapes are safe
 * whichever parser reads the file.
 *
 * @param mixed $s
 * @return string
 */
function llmstxt_escape($s)
{
    return str_replace(
        ['\\', '`', '*', '_', '[', ']', '<'],
        ['\\\\', '\\`', '\\*', '\\_', '\\[', '\\]', '\\<'],
        (string)$s
    );
}

/**
 * Text that will sit inside [ ] as a link label or after "# " as a heading:
 * one line, Markdown-escaped.
 *
 * @param mixed $s
 * @return string
 */
function llmstxt_label($s)
{
    return llmstxt_escape(trim(str_replace(["\r", "\n"], ' ', (string)$s)));
}

/**
 * A URL that is safe to sit inside ( ). Spaces and parentheses are the two
 * things that break Markdown link syntax.
 *
 * @param mixed $url
 * @return string
 */
function llmstxt_url($url)
{
    return str_replace([' ', '(', ')'], ['%20', '%28', '%29'], trim((string)$url));
}

/**
 * One "- [label](url): notes" line, or "- [label](url)" when there are no notes.
 *
 * @param string $label
 * @param string $url
 * @param string $notes
 * @return string
 */
function llmstxt_item($label, $url, $notes = '')
{
    $line = '- [' . llmstxt_label($label) . '](' . llmstxt_url($url) . ')';
    $notes = llmstxt_escape(trim(str_replace(["\r", "\n"], ' ', (string)$notes)));
    if ($notes !== '') {
        $line .= ': ' . $notes;
    }
    return $line;
}

/**
 * A price for the listing, in the store's default currency.
 *
 * Formatted from the currencies table rather than the storefront's $currencies
 * object, which does not exist in the admin. The tax-free base price is used:
 * a file read by a machine is better off with the unambiguous figure.
 *
 * @param float      $price
 * @param array|null $currency  row from llmstxt_default_currency()
 * @return string
 */
function llmstxt_format_price($price, $currency)
{
    $price = (float)$price;
    if (!is_array($currency)) {
        return number_format($price, 2, '.', '');
    }
    $decimals = (int)$currency['decimal_places'];
    $formatted = number_format(
        $price * (float)$currency['value'],
        $decimals,
        (string)$currency['decimal_point'],
        (string)$currency['thousands_point']
    );
    return (string)$currency['symbol_left'] . $formatted . (string)$currency['symbol_right'];
}

